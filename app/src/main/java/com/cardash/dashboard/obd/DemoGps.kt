    private val N = ROUTE.size / 2

    /** Latest simulated position, or null when demo mode isn't running. */
    @Volatile var fix: Fix? = null
        private set
    private var seg = 0
    private var along = 0.0

    fun reset() { fix = null; seg = 0; along = 0.0 }

    /** Drive [speedKmh] for [dt] seconds along the tour. */
    fun advance(speedKmh: Double, dt: Double) {
        var d = (speedKmh / 3.6 * dt).coerceAtLeast(0.0)
        var guard = 0
        while (guard++ < 256) {
            val len = segLength(seg)
            if (along + d <= len) { along += d; break }
            d -= len - along
            along = 0.0
            seg = (seg + 1) % N
        }
        val a = seg * 2
        val b = ((seg + 1) % N) * 2
        val len = segLength(seg)
        val f = if (len > 0) along / len else 0.0
        val lat = ROUTE[a] + (ROUTE[b] - ROUTE[a]) * f
        val lng = ROUTE[a + 1] + (ROUTE[b + 1] - ROUTE[a + 1]) * f
        fix = Fix(lat, lng, bearing(ROUTE[a], ROUTE[a + 1], ROUTE[b], ROUTE[b + 1]), speedKmh / 3.6, altitudeAt(lng))
    }

    /**
     * Rough ground height above sea level along the tour, for Google's 3D camera: Park Lane and Hyde Park Corner
     * about 25 m, Buckingham Palace and The Mall about 10 m, Trafalgar Square about 14 m, the riverside about 6 m.
     */
    private fun altitudeAt(lng: Double) = when {
        lng < -0.150 -> 25.0
        lng < -0.135 -> 10.0
        lng < -0.124 -> 14.0
        else -> 6.0
    }

    private fun segLength(i: Int): Double {
        val a = i * 2
        val b = ((i + 1) % N) * 2
        return metres(ROUTE[a], ROUTE[a + 1], ROUTE[b], ROUTE[b + 1])
    }

    private fun metres(lat1: Double, lng1: Double, lat2: Double, lng2: Double): Double {
        val r = 6_371_000.0
        val p1 = Math.toRadians(lat1)
        val p2 = Math.toRadians(lat2)
        val dp = p2 - p1
        val dl = Math.toRadians(lng2 - lng1)
        val h = sin(dp / 2) * sin(dp / 2) + cos(p1) * cos(p2) * sin(dl / 2) * sin(dl / 2)
        return 2 * r * atan2(sqrt(h), sqrt(1 - h))
    }

    private fun bearing(lat1: Double, lng1: Double, lat2: Double, lng2: Double): Double {
        val p1 = Math.toRadians(lat1)
        val p2 = Math.toRadians(lat2)
        val dl = Math.toRadians(lng2 - lng1)
        val y = sin(dl) * cos(p2)
        val x = cos(p1) * sin(p2) - sin(p1) * cos(p2) * cos(dl)
        return (Math.toDegrees(atan2(y, x)) + 360) % 360
    }
